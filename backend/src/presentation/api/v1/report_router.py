@router.get(
    "",
    response_model=ReportListResponse,
    summary="List all reports generated by user (Admin only)",
)
async def list_reports(
    current_user: User = Depends(require_admin),
    report_service: ReportService = Depends(get_report_service),
):
    reports = await report_service.list_user_reports(user_id=current_user.id)
    items = [SupportReportResponse.model_validate(r) for r in reports]
    return ReportListResponse(items=items, total=len(items))


@router.get(
    "/{report_id}",
    response_model=SupportReportResponse,
    summary="Get report details by ID (Admin only)",
)
async def get_report_by_id(
    report_id: str,
    current_user: User = Depends(require_admin),
    report_service: ReportService = Depends(get_report_service),
):
    try:
        report = await report_service.get_report_by_id(
            user_id=current_user.id,
            report_id=report_id,
        )
        return SupportReportResponse.model_validate(report)
    except ReportNotFoundError as e:
        raise HTTPException(status_code=status.HTTP_404_NOT_FOUND, detail=str(e))


@router.get(
    "/{report_id}/export/pdf",
    summary="Export executive analytics report as PDF document (Admin only)",
)
@router.get(
    "/{report_id}/pdf",
    summary="Export executive analytics report as PDF document alias (Admin only)",
)
async def export_report_pdf(
    report_id: str,
    current_user: User = Depends(require_admin),
    report_service: ReportService = Depends(get_report_service),
):
    try:
        pdf_bytes = await report_service.export_report_pdf(
            user_id=current_user.id,
            report_id=report_id,
        )
        return Response(
            content=pdf_bytes,
            media_type="application/pdf",
            headers={"Content-Disposition": f"attachment; filename=executive_report_{report_id[:8]}.pdf"},
        )
    except ReportNotFoundError as e:
        raise HTTPException(status_code=status.HTTP_404_NOT_FOUND, detail=str(e))
